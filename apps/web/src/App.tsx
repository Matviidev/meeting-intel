import clsx from 'clsx';
import { Menu, PanelRight, RotateCcw, X } from 'lucide-react';
import { useEffect, useMemo, useRef, useState } from 'react';
import { ActionBoard } from './components/ActionBoard';
import { Composer } from './components/Composer';
import { EmptyState } from './components/EmptyState';
import { MeetingList } from './components/MeetingList';
import { MeetingPanel } from './components/MeetingPanel';
import { MessageView } from './components/MessageView';
import { SourcesPanel } from './components/SourcesPanel';
import { TracePanel } from './components/TracePanel';
import type { Focus } from './components/Transcript';
import { Button, IconButton } from './components/ui';
import { useMeetings } from './hooks/queries';
import { useChat } from './hooks/useChat';
import type { ActionItem, Source } from './lib/types';

type Tab = 'meeting' | 'actions' | 'sources' | 'trace';

const TABS: { id: Tab; label: string }[] = [
  { id: 'meeting', label: 'Meeting' },
  { id: 'actions', label: 'Actions' },
  { id: 'sources', label: 'Sources' },
  { id: 'trace', label: 'Trace' },
];

function Brand() {
  return (
    <div className="flex items-center gap-2.5">
      <img src="/favicon.svg" alt="" className="size-7" />
      <span className="font-serif text-2xl leading-none">Quorum</span>
    </div>
  );
}

export function App() {
  const meetingsQuery = useMeetings();
  const meetings = useMemo(() => meetingsQuery.data ?? [], [meetingsQuery.data]);
  const chat = useChat();

  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [focus, setFocus] = useState<Focus | null>(null);
  const [pinned, setPinned] = useState<number[]>([]);
  const [tab, setTab] = useState<Tab>('meeting');
  const [draft, setDraft] = useState<{ text: string; nonce: number } | null>(null);
  const [activeId, setActiveId] = useState<string | null>(null);
  const [highlight, setHighlight] = useState<string | null>(null);
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [inspectorOpen, setInspectorOpen] = useState(false);
  const bottomRef = useRef<HTMLDivElement>(null);

  const numbers = useMemo(() => new Set(meetings.map((m) => m.number)), [meetings]);
  const visiblePinned = pinned.filter((n) => numbers.has(n));
  const selected = meetings.find((m) => m.id === selectedId);
  const lastAnswer = [...chat.messages].reverse().find((m) => m.role === 'assistant');
  const activeMessage = chat.messages.find((m) => m.id === activeId) ?? lastAnswer;

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' });
  }, [chat.messages.length, lastAnswer?.content.length]);

  const openInspector = (next: Tab) => {
    setTab(next);
    setInspectorOpen(true);
  };

  const send = (question: string) => {
    setActiveId(null);
    setHighlight(null);
    void chat.send(question, visiblePinned);
  };

  const openMoment = (meetingId: string | undefined, sec: number | null) => {
    if (!meetingId) return;
    setSelectedId(meetingId);
    openInspector('meeting');
    if (sec !== null) setFocus({ sec, nonce: Date.now() });
  };

  const jumpTo = (item: ActionItem) => openMoment(item.meetingId, item.atSec);
  const openSource = (s: Source) =>
    openMoment(meetings.find((m) => m.number === s.meetingNumber)?.id, s.startSec);

  const focusMeeting = (n: number) => {
    setPinned((p) => (p.includes(n) ? [] : [n]));
    setInspectorOpen(false);
    if (!pinned.includes(n)) setDraft({ text: '', nonce: Date.now() });
  };

  const sidebar = (
    <div className="flex h-full flex-col gap-6 overflow-y-auto p-5">
      <div className="flex items-center justify-between">
        <Brand />
        <IconButton label="Close menu" className="md:hidden" onClick={() => setSidebarOpen(false)}>
          <X className="size-4" />
        </IconButton>
      </div>
      <MeetingList
        meetings={meetings}
        loading={meetingsQuery.isLoading}
        selectedId={selectedId}
        onSelect={(m) => {
          setSelectedId(m?.id ?? null);
          setSidebarOpen(false);
          if (m) openInspector('meeting');
        }}
      />
      <p className="mt-auto text-[11px] leading-relaxed text-muted">
        Transcripts stay in your own database. Answers are generated by Claude from retrieved
        excerpts and link back to the moment they were said.
      </p>
    </div>
  );

  const inspector = (
    <div className="flex h-full flex-col">
      <div className="flex items-center gap-1 border-b border-line px-3 pt-3">
        {TABS.map((t) => (
          <button
            key={t.id}
            type="button"
            onClick={() => setTab(t.id)}
            className={clsx(
              '-mb-px border-b-2 px-2.5 pb-2.5 text-sm font-medium transition-colors',
              tab === t.id
                ? 'border-accent text-ink'
                : 'border-transparent text-muted hover:text-ink',
            )}
            aria-current={tab === t.id}
          >
            {t.label}
          </button>
        ))}
        <IconButton
          label="Close panel"
          className="mb-2 ml-auto lg:hidden"
          onClick={() => setInspectorOpen(false)}
        >
          <X className="size-4" />
        </IconButton>
      </div>
      <div className="flex-1 overflow-y-auto p-5">
        {tab === 'meeting' && (
          <MeetingPanel
            meetingId={selectedId}
            focus={focus}
            pinned={!!selected && visiblePinned.includes(selected.number)}
            onSeek={(sec) => setFocus({ sec, nonce: Date.now() })}
            onAsk={focusMeeting}
          />
        )}
        {tab === 'actions' && <ActionBoard onJump={jumpTo} />}
        {tab === 'sources' && (
          <SourcesPanel message={activeMessage} highlight={highlight} onOpen={openSource} />
        )}
        {tab === 'trace' && <TracePanel message={activeMessage} />}
      </div>
    </div>
  );

  return (
    <div className="grid h-full grid-cols-1 md:grid-cols-[300px_1fr] lg:grid-cols-[300px_1fr_440px]">
      <aside className="hidden border-r border-line bg-paper md:block">{sidebar}</aside>

      {sidebarOpen && (
        <div className="fixed inset-0 z-40 md:hidden">
          <div className="absolute inset-0 bg-ink/30" onClick={() => setSidebarOpen(false)} />
          <aside className="absolute inset-y-0 left-0 w-[86%] max-w-sm bg-paper shadow-xl">
            {sidebar}
          </aside>
        </div>
      )}

      <main className="flex min-h-0 min-w-0 flex-col">
        <header className="flex items-center gap-2 border-b border-line px-4 py-2.5 md:px-6">
          <IconButton label="Open menu" className="md:hidden" onClick={() => setSidebarOpen(true)}>
            <Menu className="size-4" />
          </IconButton>
          <div className="md:hidden">
            <Brand />
          </div>
          <p className="hidden text-sm text-muted md:block">
            {meetings.length
              ? `${meetings.length} meeting${meetings.length > 1 ? 's' : ''} indexed`
              : 'No meetings yet'}
          </p>
          <div className="ml-auto flex items-center gap-1">
            {chat.messages.length > 0 && (
              <Button variant="ghost" onClick={chat.reset}>
                <RotateCcw className="size-3.5" /> New chat
              </Button>
            )}
            <IconButton
              label="Open insights panel"
              className="lg:hidden"
              onClick={() => setInspectorOpen(true)}
            >
              <PanelRight className="size-4" />
            </IconButton>
          </div>
        </header>

        <div className="flex-1 overflow-y-auto px-4 md:px-6">
          <div className="mx-auto max-w-3xl space-y-4 py-6">
            {chat.messages.length === 0 ? (
              <EmptyState meetings={meetings} onPick={send} />
            ) : (
              chat.messages.map((m) => (
                <MessageView
                  key={m.id}
                  message={m}
                  active={m.id === activeMessage?.id && (tab === 'sources' || tab === 'trace')}
                  onCite={(label) => {
                    setActiveId(m.id);
                    setHighlight(label);
                    openInspector('sources');
                  }}
                  onShowSources={() => {
                    setActiveId(m.id);
                    setHighlight(null);
                    openInspector('sources');
                  }}
                  onRate={(v) => m.meta && chat.rate(m.id, m.meta.traceId, v)}
                />
              ))
            )}
            <div ref={bottomRef} />
          </div>
        </div>

        <div className="px-4 pb-4 md:px-6 md:pb-6">
          <div className="mx-auto max-w-3xl">
            <Composer
              disabled={!meetings.length}
              streaming={chat.streaming}
              pinned={visiblePinned}
              meetings={meetings}
              draft={draft}
              onUnpin={(n) => setPinned((p) => p.filter((x) => x !== n))}
              onSend={send}
              onStop={chat.stop}
            />
            <p className="mt-2 text-center text-[11px] text-muted">
              Answers can be wrong. Check the cited moments before relying on them.
            </p>
          </div>
        </div>
      </main>

      <aside className="hidden border-l border-line bg-paper lg:block">{inspector}</aside>

      {inspectorOpen && (
        <div className="fixed inset-0 z-40 lg:hidden">
          <div className="absolute inset-0 bg-ink/30" onClick={() => setInspectorOpen(false)} />
          <aside className="absolute inset-y-0 right-0 w-full max-w-md bg-paper shadow-xl">
            {inspector}
          </aside>
        </div>
      )}
    </div>
  );
}
